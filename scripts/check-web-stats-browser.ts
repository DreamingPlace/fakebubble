/**
 * Part 22c: 玩家统计, 消耗表 and 概览 in a REAL browser (Chromium), on the console as an owner sees it. The database is a real
 * migrated provider-local instance whose clock stands on 2026-11-20 (so the month holds 2026-11-12, the day Fish Drama 3's list
 * price changes) and whose counters started on 2026-11-03. The numbers are SYNTHETIC: generated by a seeded generator and written
 * straight into web_stats_daily / web_provider_usage, so a screenshot shows the layout of a busy site, not a real one. What the
 * real pipeline writes is tested by web-stats-22c-http (workerd). The check also saves both CSVs from the buttons and a second,
 * administrator without stats.read, who sees neither page.
 *
 * usage: node scripts/check-web-stats-browser.ts [screenshot-dir]   (run `pnpm web:player:build` first)
 * Playwright is resolved like check-web-invite-codes-browser.ts (PLAYWRIGHT_MODULE, the working tree, the usual tool directories).
 */
const shots = process.argv[2] ? resolve(process.argv[2]) : null;
if (shots) mkdirSync(shots, { recursive: true });

// biome-ignore lint/suspicious/noExplicitAny: untyped optional tool
function loadPlaywright(): any {
  const candidates = [
    process.env.PLAYWRIGHT_MODULE,
    'playwright',
    '/node-tools/node_modules/playwright',
    '/opt/node22/lib/node_modules/playwright',
  ].filter(Boolean) as string[];
  for (const candidate of candidates) {
    try {
      return createRequire(import.meta.url)(candidate);
    } catch {
      /* try the next one */
    }
  }
  throw new Error('Playwright is not installed: set PLAYWRIGHT_MODULE to its directory');
}

const DAY = 86_400_000;
const NOW = Date.parse('2026-11-20T10:00:00Z');
const STARTED = Date.parse('2026-11-03T08:00:00Z');
const day = (at: number) => new Date(at).toISOString().slice(0, 10);
const { parent } = localRuntime();
mkdirSync(parent, { recursive: true, mode: 0o700 });
const root = join(parent, `provider-stats-${randomUUID().slice(0, 12)}`);
initProviderInstance(root);
migrateProvider(root, syntheticSelection(), STARTED);
const { config, store } = openProviderStore(root);
const clock = { now: () => NOW };

// ---- synthetic history (a seeded generator, so a re-run draws the same picture) ----
let seed = 22_011_120;
const rnd = (max: number) => {
  seed = (seed * 1_664_525 + 1_013_904_223) % 4_294_967_296;
  return Math.floor((seed / 4_294_967_296) * max);
};
const put = (d: string, metric: string, value: number, characterId = '', model = '') =>
  store.run(
    `INSERT INTO web_stats_daily(day,metric,character_id,model,value) VALUES (?,?,?,?,?)
    ON CONFLICT(day,metric,character_id,model) DO UPDATE SET value=value+excluded.value`,
    d,
    metric,
    characterId,
    model,
    value,
  );
const CHARACTERS = ['wei-guagua', 'jojo', 'chen-jimi'];
const MODELS = ['', 'deepseek', 'gemini', 'xai'];
for (let at = Date.parse('2026-11-03T00:00:00Z'); at <= NOW; at += DAY) {
  const d = day(at),
    signups = 2 + rnd(7),
    guests = 10 + rnd(25);
  put(d, 'signups', signups);
  put(d, 'new_guests', guests);
  put(d, 'active_registered', 18 + rnd(30));
  put(d, 'active_guest', guests + rnd(10));
  put(d, 'chat_registered', 9 + rnd(18));
  put(d, 'chat_guest', Math.floor(guests * 0.7));
  put(d, 'purge_expired', rnd(Math.max(1, Math.floor(guests / 3))));
  if (rnd(4) === 0) put(d, 'purge_deleted', 1 + rnd(2));
  if (rnd(6) === 0) put(d, 'purge_inactive', 1 + rnd(2));
  for (const characterId of CHARACTERS)
    for (const model of MODELS) {
      if (rnd(3) === 0) continue;
      const published = 8 + rnd(40);
      put(d, 'reply_published', published, characterId, model);
      put(d, 'reply_voice', Math.floor(published * 0.85), characterId, model);
      if (rnd(3) === 0) put(d, 'reply_failed', 1 + rnd(3), characterId, model);
      if (rnd(12) === 0) put(d, 'reply_unknown', 1, characterId, model);
      if (model) put(d, 'points_spent', published * (model === 'xai' ? 27 : model === 'gemini' ? 22 : 12), '', model);
    }
  // A cohort closes on day +2 (D1) and +8 (D7).
  if (at <= NOW - 2 * DAY) {
    put(d, 'd1_cohort', signups);
    put(d, 'd1_retained', Math.round(signups * (0.3 + rnd(30) / 100)));
  }
  if (at <= NOW - 8 * DAY) {
    put(d, 'd7_cohort', signups);
    put(d, 'd7_retained', Math.round(signups * (0.1 + rnd(25) / 100)));
  }
}
// Consumption since the owner's first usage rows (21b), the days before 22c with no ledger amount.
const usage = (d: string, provider: string, model: string, phase: string, calls: number, units: number, bytes = 0) => {
  const input = phase === 'speech' ? 0 : units,
    output = phase === 'speech' ? 0 : Math.round(units / 6);
  const cost =
    phase === 'speech'
      ? bytes * speechListMicrosPerByte(model, d)
      : listPriceMicros(provider, model, {
          inputTokens: input,
          cachedInputTokens: Math.round(input * 0.4),
          outputTokens: output,
        });
  store.run(
    `INSERT INTO web_provider_usage(day,provider,model,phase,calls,input_tokens,cached_input_tokens,output_tokens,bytes,cost_micros,replies,ledger_charged_micros)
    VALUES (?,?,?,?,?,?,?,?,?,?,?,?)`,
    d,
    provider,
    model,
    phase,
    calls,
    input,
    Math.round(input * 0.4),
    output,
    bytes,
    cost,
    phase === 'speech' ? 0 : calls,
    d >= day(STARTED) ? Math.round(cost * 1.8) : 0,
  );
};
for (let at = Date.parse('2026-10-18T00:00:00Z'); at <= NOW; at += DAY) {
  const d = day(at),
    n = 60 + rnd(120);
  usage(d, 'deepseek', 'deepseek-v4-flash', 'draft', n, n * (2400 + rnd(600)));
  usage(d, 'deepseek', 'deepseek-v4-flash', 'review', n, n * (1800 + rnd(400)));
  if (rnd(2)) usage(d, 'gemini', 'gemini-3.8-flash', 'draft', 12 + rnd(30), 30_000 + rnd(30_000));
  if (rnd(2)) usage(d, 'xai', 'grok-4.7', 'draft', 8 + rnd(25), 25_000 + rnd(30_000));
  usage(d, 'fish', 's2.1-pro', 'speech', n, 0, n * (260 + rnd(80)));
  if (rnd(2)) usage(d, 'fish', 'drama-3', 'speech', 10 + rnd(30), 0, (10 + rnd(30)) * 280);
}

const runner = new WebProviderRunner(
  store,
  clock,
  new DeepSeekTextGenerator({ apiKey: 'offline-only', fetch: async () => new Response('{}', { status: 500 }) }),
  async (request) => ({ audio: syntheticTone(), receipt: { id: 'fake' }, usageUnits: request.billedTextBytes }),
);
const app = new WebProviderServer(store, config, clock, runner, undefined, undefined, { signupEnabled: false });
await app.listen();

const { chromium } = loadPlaywright();
const browser = await chromium.launch(
  process.env.PLAYWRIGHT_CHROMIUM ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM } : {},
);
const origin = new URL(config.origin).origin;
const API = `${origin}/api/web/provider`;
let failure: unknown;
try {
  const errors: string[] = [];
  const admins = new WebAccountAdmin(store, clock, config.origin);
  const login = async (token: string) => {
    const context = await browser.newContext({ ignoreHTTPSErrors: true, viewport: { width: 1800, height: 1500 } });
    const response = await context.request.post(`${API}/admin/login`, {
      data: { token },
      headers: { origin: config.origin },
    });
    assert.equal(response.status(), 200);
    return { context, csrf: (await response.json()).csrf as string };
  };
  const owner = await login(admins.issueLoginGrant().token);
  const plain = await login(
    (
      await (
        await owner.context.request.post(`${API}/admin/members/issue`, {
          data: { requestId: randomUUID(), label: 'no stats', memberId: null, permissions: ['invites.manage'] },
          headers: { origin: config.origin, 'x-csrf-token': owner.csrf },
        })
      ).json()
    ).token,
  );
  // biome-ignore lint/suspicious/noExplicitAny: untyped optional tool
  const open = async (actor: { context: any }, route: string) => {
    const page = await actor.context.newPage();
    page.on('pageerror', (error: unknown) => errors.push(String(error)));
    await page.goto(`${origin}/?mode=provider-admin#/${route}`);
    return page;
  };
  // biome-ignore lint/suspicious/noExplicitAny: untyped optional tool
  const shot = async (page: any, name: string, fullPage = false) => {
    await page.waitForTimeout(700);
    if (shots) await page.screenshot({ path: join(shots, `${name}.png`), fullPage });
  };

  // ---- 概览: yesterday and this month's spend ----
  const overview = await open(owner, 'overview');
  await overview.getByText('昨日新注册').waitFor({ timeout: 20_000 });
  await overview.getByText('本月花费').waitFor();
  await shot(overview, 'overview-with-stats-line');

  // ---- 玩家统计: 7 days, 30 days, 按角色, 按模型 ----
  const stats = await open(owner, 'stats');
  await stats.getByText('统计自 2026-11-03 起（UTC）').waitFor({ timeout: 20_000 });
  await stats.locator('#admin-stats table tbody tr').first().waitFor();
  assert.equal(
    await stats.locator('#admin-stats table:has(caption:text-is("玩家统计（按天）")) tbody tr').count(),
    8,
    '7 days and the totals row',
  );
  await shot(stats, 'player-stats-7-days');
  await stats.locator('#admin-stats select').selectOption('30');
  await stats.waitForFunction(
    () => (document.querySelectorAll('#admin-stats table tbody tr') as NodeListOf<Element>).length > 10,
  );
  assert.equal(
    await stats.locator('#admin-stats table:has(caption:text-is("玩家统计（按天）")) tbody tr').count(),
    19,
    'from the start day: 18 days and the totals',
  );
  await shot(stats, 'player-stats-30-days', true);
  await stats.getByRole('tab', { name: '按角色' }).click();
  await shot(stats, 'player-stats-by-character');
  await stats.getByRole('tab', { name: '按模型' }).click();
  await shot(stats, 'player-stats-by-model');
  const body = await stats.locator('body').innerText();
  for (const id of CHARACTERS) assert.equal(body.includes(id), false, `no character id on the page: ${id}`);
  const [statsCsv] = await Promise.all([
    stats.waitForEvent('download'),
    stats.getByRole('button', { name: '导出表格' }).click(),
  ]);
  const statsBytes = readFileSync(await statsCsv.path());
  assert.deepEqual([...statsBytes.subarray(0, 3)], [0xef, 0xbb, 0xbf], 'a UTF-8 BOM');
  assert.equal(statsBytes.toString('utf8').trimEnd().split('\r\n').length, 1 + 18 + 1);

  // ---- 消耗表: the month spans 2026-11-12 ----
  const costs = await open(owner, 'costs');
  await costs.getByText('按 1 美元 ≈ 6.7 元估算').waitFor({ timeout: 20_000 });
  await costs.getByText('Fish Drama 3 的列表价').waitFor();
  await shot(costs, 'costs-month-spanning-2026-11-12', true);
  const [costsCsv] = await Promise.all([
    costs.waitForEvent('download'),
    costs.getByRole('button', { name: '导出表格' }).click(),
  ]);
  assert.deepEqual([...readFileSync(await costsCsv.path()).subarray(0, 3)], [0xef, 0xbb, 0xbf]);

  // ---- an administrator without stats.read sees neither page ----
  const other = await open(plain, 'stats');
  await other.waitForTimeout(1500);
  assert.equal(await other.getByText('统计自').count(), 0);
  assert.equal(await other.getByRole('link', { name: '玩家统计' }).count(), 0);
  assert.equal(await other.getByRole('link', { name: '消耗表' }).count(), 0);
  assert.equal(
    (
      await plain.context.request.post(`${API}/admin/stats/players`, {
        data: { range: 7 },
        headers: { origin: config.origin, 'x-csrf-token': plain.csrf },
      })
    ).status(),
    403,
  );
  assert.deepEqual(errors, [], 'no uncaught page errors');
  process.stdout.write('stats browser check: PASS\n');
} catch (error) {
  failure = error;
} finally {
  await browser.close();
  await app.close();
  store.close();
}
if (failure) {
  console.error(failure);
  process.exitCode = 1;
}
