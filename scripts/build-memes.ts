// Part 37c-1: the internet-meme dictionary ships as DATA with the build (no runtime fetch).
//   node scripts/build-memes.ts --import <memes.json> --commit <sha>   keep only 2022+ entries into the reviewed data file
//   node scripts/build-memes.ts                                        write apps/server/memes/meme-dictionary.generated.ts
//   node scripts/build-memes.ts --check                                fail when either file is stale (part of `pnpm check`)
// Source: re-skylar/chinese-meme-dict, data/memes.json ({t, m, o, d, tag}), CC BY 4.0. The notice below is REQUIRED by that license.
import { readFileSync, writeFileSync } from 'node:fs';
import { MEME_CATEGORIES, isKeptCategory } from '../packages/contracts/web-memes.ts';

export const MEME_NOTICE = 'chinese-meme-dict — 作者：sky（出力）、楠（出token）— CC BY 4.0';
export const MEME_SOURCE_URL = 'https://github.com/re-skylar/chinese-meme-dict';
/** Owner decision (Part 37c-1): only entries dated 2022 or later; an undated entry is dropped. */
export const MEME_MIN_YEAR = 2022;
const DATA = new URL('../data/chinese-meme-dict/memes-2022plus.json', import.meta.url);
const GENERATED = new URL('../apps/server/memes/meme-dictionary.generated.ts', import.meta.url);

interface Source {
  t: string;
  m: string;
  o: string;
  d: string;
  tag: string[];
  /** Part 37c-1b: the category (one of MEME_CATEGORIES). */
  c?: string;
  /** Part 37c-1 follow-up: 1 = a common everyday word, shipped DEFAULT OFF (the owner's per-entry switch overrides it both ways). */
  x?: 1;
}
/**
 * An entry whose whole term is a common everyday word starts switched OFF, so it never fires in normal chat. Decided by code from a
 * public word-frequency list: jieba's `jieba/dict.txt` (MIT, Sun Junyi), any term of any length, frequency >= JIEBA_MIN_FREQ.
 */
export const JIEBA_MIN_FREQ = 20;
export const JIEBA_SOURCE = {
  url: 'https://github.com/fxsjy/jieba',
  file: 'jieba/dict.txt',
  license: 'MIT (Copyright (c) 2013 Sun Junyi)',
};
export function markDefaultOff(entries: readonly Source[], dict: ReadonlyMap<string, number>): Source[] {
  return entries.map((entry) => {
    const { x: _drop, ...rest } = entry;
    return (dict.get(entry.t) ?? 0) >= JIEBA_MIN_FREQ ? { ...rest, x: 1 as const } : rest;
  });
}
export const readJieba = (path: string): Map<string, number> => {
  const dict = new Map<string, number>();
  for (const line of readFileSync(path, 'utf8').split('\n')) {
    const [word, freq] = line.split(' ');
    if (word && freq) dict.set(word, Number(freq));
  }
  return dict;
};
interface DataFile {
  schema: 1;
  license: 'CC-BY-4.0';
  notice: string;
  source: { url: string; commit: string; file: 'data/memes.json'; filter: string };
  count: number;
  defaultOff: { source: typeof JIEBA_SOURCE & { commit: string }; minFreq: number; count: number };
  curation: ReturnType<typeof curationCounts>;
  entries: Source[];
}

export function filterEntries(entries: readonly Source[]): Source[] {
  return entries.filter((entry) => /^\d{4}$/u.test(entry.d) && Number(entry.d) >= MEME_MIN_YEAR);
}
const line = (entry: Source) =>
  `  ${JSON.stringify({ t: entry.t, m: entry.m, o: entry.o, d: entry.d, tag: entry.tag, c: entry.c ?? '', ...(entry.x ? { x: 1 } : {}) })}`;
/** An entry ships ON only when it was kept AND is not an everyday word. */
export const shipsOff = (entry: Pick<Source, 'c' | 'x'>) => !isKeptCategory(entry.c ?? '') || entry.x === 1;
export const curationCounts = (entries: readonly Pick<Source, 'c'>[]) => {
  const byCategory: Record<string, number> = {};
  for (const category of MEME_CATEGORIES) byCategory[category] = entries.filter((entry) => entry.c === category).length;
  return { kept: entries.filter((entry) => isKeptCategory(entry.c ?? '')).length, byCategory };
};
export function renderData(entries: readonly Source[], commit: string, jiebaCommit: string): string {
  const head = {
    schema: 1,
    license: 'CC-BY-4.0',
    notice: MEME_NOTICE,
    source: {
      url: MEME_SOURCE_URL,
      commit,
      file: 'data/memes.json',
      filter: `d >= ${MEME_MIN_YEAR}; undated entries dropped`,
    },
    count: entries.length,
    defaultOff: {
      source: { ...JIEBA_SOURCE, commit: jiebaCommit },
      minFreq: JIEBA_MIN_FREQ,
      count: entries.filter((entry) => entry.x).length,
    },
    curation: curationCounts(entries),
  };
  const top = JSON.stringify(head).slice(0, -1);
  return `${top},"entries":[\n${entries.map(line).join(',\n')}\n]}\n`;
}
/** The generated module: [term, meaning, year, tags]. The origin note `o` stays in the data file only. */
export function renderModule(file: DataFile): string {
  const rows = file.entries.map(
    (entry) =>
      `  ${JSON.stringify([entry.t, entry.m, Number(entry.d), entry.tag, shipsOff(entry), entry.c, entry.x === 1])},`,
  );
  return [
    '// GENERATED by scripts/build-memes.ts from data/chinese-meme-dict/memes-2022plus.json. Do not edit; run `pnpm memes:build`.',
    `// ${MEME_NOTICE} — ${MEME_SOURCE_URL}`,
    `// source commit ${file.source.commit}`,
    '// row: [term, meaning, year, tags, ships OFF, category, everyday word (jieba)]',
    'export const MEME_DICTIONARY_ROWS: readonly (readonly [string, string, number, readonly string[], boolean, string, boolean])[] = [',
    ...rows,
    '];',
    '',
  ].join('\n');
}
export const readData = (): DataFile => JSON.parse(readFileSync(DATA, 'utf8')) as DataFile;

function main() {
  const args = process.argv.slice(2);
  const at = (flag: string) => args[args.indexOf(flag) + 1];
  if (args.includes('--import')) {
    const commit = at('--commit');
    if (!commit || !/^[0-9a-f]{40}$/u.test(commit))
      throw new Error('--commit <40-hex sha of the source checkout> is required');
    const jiebaCommit = at('--jieba-commit');
    const jieba = at('--jieba');
    if (!jiebaCommit || !/^[0-9a-f]{40}$/u.test(jiebaCommit) || !jieba)
      throw new Error('--jieba <dict.txt> --jieba-commit <sha of the jieba checkout> are required');
    const source = JSON.parse(readFileSync(at('--import')!, 'utf8')) as { entries: Source[] };
    // Part 37c-1b: the hand-made categories are kept by term; a term that is new has none yet and fails --check until it is judged.
    const known = new Map(readData().entries.map((entry) => [entry.t, entry.c] as const));
    const withCategory = filterEntries(source.entries).map((entry) => ({ ...entry, c: known.get(entry.t) ?? '' }));
    writeFileSync(DATA, renderData(markDefaultOff(withCategory, readJieba(jieba)), commit, jiebaCommit));
  }
  const data = readData();
  const module = renderModule(data);
  if (args.includes('--check')) {
    const stale = readFileSync(GENERATED, 'utf8') !== module;
    const filtered =
      filterEntries(data.entries).length !== data.entries.length ||
      data.count !== data.entries.length ||
      data.defaultOff.count !== data.entries.filter((entry) => entry.x).length ||
      data.entries.some((entry) => !MEME_CATEGORIES.includes(entry.c ?? '')) ||
      JSON.stringify(data.curation) !== JSON.stringify(curationCounts(data.entries));
    if (stale || filtered || data.notice !== MEME_NOTICE) {
      console.error('The meme dictionary is stale; run `pnpm memes:build`.');
      process.exit(1);
    }
    return;
  }
  writeFileSync(GENERATED, module);
  console.log(`memes: ${data.entries.length} entries (commit ${data.source.commit})`);
}
if (import.meta.main) main();
