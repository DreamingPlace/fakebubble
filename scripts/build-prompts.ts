// Workers have no filesystem: bake prompts/v7/*.md into a committed TS module.
// `node scripts/build-prompts.ts` writes it; `--check` fails when the committed module is stale.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const PROMPT_DIR = new URL('../prompts/v7/', import.meta.url);
export const GENERATED_PROMPTS = new URL('../apps/server/generation/prompts.generated.ts', import.meta.url);
/** Part 24a: the cast prompt files (cast-*.md) live in their own module, so the chat prompt hash and PROMPTS_V7 are unchanged. */
export const GENERATED_CAST_PROMPTS = new URL('../apps/server/generation/cast-prompts.generated.ts', import.meta.url);
/** Part 24c: the seed-character prompt files (seed-*.md) likewise live in their own module. */
export const GENERATED_SEED_PROMPTS = new URL('../apps/server/generation/seed-prompts.generated.ts', import.meta.url);
/** Part 30: the clip-direction prompt (clip-*.md) likewise lives in its own module. */
export const GENERATED_CLIP_PROMPTS = new URL('../apps/server/generation/clip-prompts.generated.ts', import.meta.url);
/** Part 37a: the v8 writer prompt files (prompts/v8/*.md) live in their own module, so every v7 hash is unchanged. */
const WRITER_DIR = new URL('../prompts/v8/', import.meta.url);
export const GENERATED_WRITER_PROMPTS = new URL(
  '../apps/server/generation/writer-prompts.generated.ts',
  import.meta.url,
);
const isCast = (file: string) => file.startsWith('cast-');
const isClip = (file: string) => file.startsWith('clip-');
const isSeed = (file: string) => file.startsWith('seed-');

const camel = (name: string) => name.replace(/-([a-z])/gu, (_, letter: string) => letter.toUpperCase());

/** Each file is the prompt block plus exactly one terminating newline, which is not part of the block. */
export function renderPromptsModule(dir: URL = PROMPT_DIR): string {
  return render(dir, (file) => !isCast(file) && !isSeed(file) && !isClip(file), 'PROMPTS_V7');
}
export function renderSeedPromptsModule(dir: URL = PROMPT_DIR): string {
  return render(dir, isSeed, 'PROMPTS_SEED');
}
export function renderClipPromptsModule(dir: URL = PROMPT_DIR): string {
  return render(dir, isClip, 'PROMPTS_CLIP');
}
export function renderWriterPromptsModule(dir: URL = WRITER_DIR): string {
  return render(dir, () => true, 'PROMPTS_V8', 'prompts/v8/*.md');
}
export function renderCastPromptsModule(dir: URL = PROMPT_DIR): string {
  return render(dir, isCast, 'PROMPTS_CAST');
}
function render(dir: URL, keep: (file: string) => boolean, name: string, source?: string): string {
  const files = readdirSync(dir)
    .filter((file) => file.endsWith('.md') && keep(file))
    .sort();
  const lines = files.map((file) => {
    const raw = readFileSync(new URL(file, dir), 'utf8');
    if (!raw.endsWith('\n')) throw new Error(`${file} must end with a newline`);
    return `  ${camel(file.slice(0, -3))}: ${JSON.stringify(raw.slice(0, -1))},`;
  });
  return [
    `// GENERATED by scripts/build-prompts.ts from ${source ?? `prompts/v7/${keep('cast-x.md') ? 'cast-*.md' : keep('seed-x.md') ? 'seed-*.md' : keep('clip-x.md') ? 'clip-*.md' : '*.md'}`}. Do not edit; run \`pnpm prompts:build\`.`,
    `export const ${name} = {`,
    ...lines,
    '} as const;',
    '',
  ].join('\n');
}

if (import.meta.main) {
  const targets = [
    [GENERATED_PROMPTS, renderPromptsModule()],
    [GENERATED_CAST_PROMPTS, renderCastPromptsModule()],
    [GENERATED_SEED_PROMPTS, renderSeedPromptsModule()],
    [GENERATED_CLIP_PROMPTS, renderClipPromptsModule()],
    [GENERATED_WRITER_PROMPTS, renderWriterPromptsModule()],
  ] as const;
  if (process.argv.includes('--check')) {
    for (const [file, next] of targets) {
      let current = '';
      try {
        current = readFileSync(file, 'utf8');
      } catch {}
      if (current !== next) {
        console.error(`${file.pathname.split('/').pop()} is stale: run \`pnpm prompts:build\` and commit the result.`);
        process.exit(1);
      }
    }
  } else for (const [file, next] of targets) writeFileSync(file, next);
}
