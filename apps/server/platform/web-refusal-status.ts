const ROUTE_ROOTS = new Set([
  'admin',
  'account',
  'cocreation',
  'public-audio',
  'sync',
  'events',
  'bootstrap',
  'history',
]);
const ADMIN_AREAS = new Set([
  'characters',
  'cast',
  'profile-import',
  'system',
  'stats',
  'review',
  'points',
  'invites',
  'members',
  'session',
  'budget',
  'models',
]);
/** A route CLASS for the log: a few fixed words, never an id, a code or a query (every other segment is dropped). */
export function routeClass(path: string): string {
  const parts = path
    .split('?')[0]!
    .replace(/^\/api\/web\/[a-z]+\/?/, '')
    .split('/')
    .filter(Boolean);
  const root = parts[0] && ROUTE_ROOTS.has(parts[0]) ? parts[0] : 'other';
  if (root === 'admin' && parts[1] && ADMIN_AREAS.has(parts[1])) return `admin/${parts[1]}`;
  return root;
}
/** One line per refusal, for the log tail. Fixed strings only. */
export function logRefusal(path: string, status: number, code: string) {
  // A code is a fixed upper-case word; anything else is never written to the log.
  const safe = /^[A-Z][A-Z0-9_]{1,63}$/.test(code) ? code : 'UNLISTED_CODE';
  console.log(JSON.stringify({ event: 'web_refusal', route: routeClass(path), status, code: safe }));
}
